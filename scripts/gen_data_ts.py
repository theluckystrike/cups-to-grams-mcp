"""Write src/data.ts from data/ingredients.json. usage: python3 -I gen_data_ts.py data/ingredients.json src/data.ts"""
import json, sys
d = json.load(open(sys.argv[1], encoding='utf8'))
body = json.dumps({'fetched': d['fetched'], 'ingredients': d['ingredients']}, ensure_ascii=False, separators=(',', ':'))
open(sys.argv[2], 'w', encoding='utf8').write('// Generated by scripts/gen_data_ts.py from data/ingredients.json. Do not edit.\nexport const DATA = ' + body + ';\n')
